export function searchKnowledge(query: string): string[] {
  const queryLower = query.toLowerCase();
  const results: string[] = [];

  const keywords: Record<string, string[]> = {
    rti_act: ["rti", "right to information", "public information", "government data", "transparency"],
    consumer_protection: ["consumer", "product", "defective", "refund", "seller", "shop", "complaint", "purchase"],
    tenant_rights: ["landlord", "tenant", "rent", "deposit", "eviction", "house owner", "lease", "rental"],
    workplace_rights: ["salary", "employer", "fired", "terminated", "wages", "pf", "provident", "workplace", "job", "labour", "maternity"],
    government_schemes: ["scheme", "yojana", "benefit", "subsidy", "eligible", "government", "pm-kisan", "mudra", "awas"],
  };

  for (const [key, terms] of Object.entries(keywords)) {
    if (terms.some((term) => queryLower.includes(term))) {
      results.push(LEGAL_KNOWLEDGE[key]);
    }
  }

  if (results.length === 0) {
    results.push(LEGAL_KNOWLEDGE.rti_act);
    results.push(LEGAL_KNOWLEDGE.consumer_protection);
    results.push(LEGAL_KNOWLEDGE.tenant_rights);
  }

  return results;
}
